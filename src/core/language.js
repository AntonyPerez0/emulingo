export function langName(code) {
  const l = LANGUAGES.find((x) => x.code === code);
  return l ? l.name : code;
}

export function langFlag(code) {
  const l = LANGUAGES.find((x) => x.code === code);
  return l ? l.flag : '🏳️';
}

// MyMemory uses e.g. "en|de"
export function myMemoryPair(src, tgt) {
  return src + '|' + tgt;
}
