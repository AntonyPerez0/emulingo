// glyph -> 8x8 array of colour indices (0 paper / 3 ink)
export function glyphPixels(ch) {
  const rows = G[ch];
  if (!rows) throw new Error('No glyph for ' + JSON.stringify(ch));
  const px = [];
  for (let y = 0; y < 8; y++) {
    const r = (rows[y] || '').padEnd(8, '.');
    if (r.length !== 8) throw new Error(`glyph ${ch} row ${y} is ${r.length} wide`);
    for (let x = 0; x < 8; x++) px.push(r[x] === '#' ? 3 : 0);
  }
  return px;
}

export function tilePixels(name) {
  const rows = T[name];
  if (!rows || rows.length !== 8) throw new Error('bad tile ' + name);
  const px = [];
  for (const r of rows) {
    if (r.length !== 8) throw new Error(`tile ${name} row width ${r.length}`);
    for (const c of r) px.push(+c);
  }
  return px;
}
