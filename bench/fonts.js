// a 1-px gap. Then the cell is shifted left by one column so the glyph
// stays centred (thin glyphs live in columns 1-5).
function boldFromThin(rows) {
  const grid = rows.map((r) => r.split('').map((c) => c === '#'));
  const out = grid.map((r) => r.slice());
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 7; x++) {
      if (!grid[y][x] || grid[y][x + 1]) continue;
      const vertical = (y > 0 && grid[y - 1][x]) || (y < 7 && grid[y + 1][x]);
      if (!vertical) continue;
      if (x + 2 < 8 && grid[y][x + 2]) continue;
      out[y][x + 1] = true;
    }
  }
  // shift left by one when column 0 is empty (keeps 2 px of spacing right)
  const col0Empty = out.every((r) => !r[0]);
  return out.map((r) => {
    const row = col0Empty ? r.slice(1).concat([false]) : r;
    return row.map((v) => (v ? '#' : '.')).join('');
  });
}

function buildBold() {
  const glyphs = {};
  for (const [ch, rows] of Object.entries(THIN_GLYPHS)) {
    glyphs[ch] = BOLD_OVERRIDES[ch] || boldFromThin(rows);
  }
  return glyphs;
}

// GBA: fixed vertical stretch 8 -> 11 rows (doubles thin rows 1, 5 and 7, so
// x-height becomes 6 rows, cap height 9, descenders 2) and proportional
// widths measured from the ink.
const GBA_ROW_MAP = [0, 1, 1, 2, 3, 4, 5, 5, 6, 7, 7];
const GBA_SPACE = 4;

function buildGba() {
  const glyphs = {};
  for (const [ch, rows] of Object.entries(THIN_GLYPHS)) {
    let x0 = 8, x1 = -1;
    for (const r of rows) {
      for (let x = 0; x < 8; x++) if (r[x] === '#') { x0 = Math.min(x0, x); x1 = Math.max(x1, x); }
    }
    if (x1 < 0) { glyphs[ch] = { rows: GBA_ROW_MAP.map(() => ''), width: 0, advance: GBA_SPACE }; continue; }
    const tall = GBA_ROW_MAP.map((src) => rows[src].slice(x0, x1 + 1));
    const width = x1 - x0 + 1;
    // 1 px of letter spacing; the drop shadow fills it
    glyphs[ch] = { rows: tall, width, advance: width + 1 };
  }
  return glyphs;
}

export const GB_THIN = { name: 'gb-thin', kind: 'tile', cell: 8, glyphs: THIN_GLYPHS };
export const GB_BOLD = { name: 'gb-bold', kind: 'tile', cell: 8, glyphs: buildBold() };
export const GBA_FONT = { name: 'gba', kind: 'prop', height: GBA_ROW_MAP.length, linePitch: 16, glyphs: buildGba() };

export function hasGlyph(font, ch) { return Object.prototype.hasOwnProperty.call(font.glyphs, ch); }

// throws on characters the font cannot draw - scene texts must never
// silently lose a character (the ground truth would then lie)
export function assertDrawable(font, text) {
  for (const ch of text) {
    if (!hasGlyph(font, ch)) throw new Error(`font ${font.name} has no glyph for ${JSON.stringify(ch)} in ${JSON.stringify(text)}`);
  }
}

// ground-truth text for a string drawn with these fonts
export function textForGroundTruth(str) {
  let out = '';
  for (const ch of str) {
    if (Object.prototype.hasOwnProperty.call(SPECIAL_TEXT, ch)) {
      const t = SPECIAL_TEXT[ch];
      out += t == null ? ' ' : t;
    } else out += ch;
  }
  return out.replace(/\s+/g, ' ').trim();
}

// --- drawing -------------------------------------------------------------

function inkPixels(ctx, rows, x, y, color, rowStart = 0) {
  ctx.fillStyle = color;
  for (let r = 0; r < rows.length; r++) {
    const row = rows[r];
    let run = -1;
    for (let c = 0; c <= row.length; c++) {
      const on = c < row.length && row[c] === '#';
      if (on && run < 0) run = c;
      if (!on && run >= 0) { ctx.fillRect(x + run, y + r + rowStart, c - run, 1); run = -1; }
    }
  }
}

// Tile font: one character per 8x8 cell, x/y in pixels. `maxChars` draws
// only a prefix (typewriter frames). Returns the x after the last cell.
export function drawTileText(ctx, font, text, x, y, color, maxChars = Infinity) {
  assertDrawable(font, text);
  let i = 0;
  for (const ch of text) {
    if (i >= maxChars) break;
    inkPixels(ctx, font.glyphs[ch], x + i * font.cell, y, color);
    i++;
  }
  return x + i * font.cell;
}

export function measurePropText(font, text) {
  let w = 0;
  for (const ch of text) w += font.glyphs[ch] ? font.glyphs[ch].advance : 0;
  return w;
}

// Proportional GBA text with a 1-px drop shadow (right, down, diagonal).
export function drawPropText(ctx, font, text, x, y, color, shadow, maxChars = Infinity) {
  assertDrawable(font, text);
  let cx = x, i = 0;
  for (const ch of text) {
    if (i >= maxChars) break;
    const g = font.glyphs[ch];
    if (g.width) {
      if (shadow) {
        inkPixels(ctx, g.rows, cx + 1, y, shadow);
        inkPixels(ctx, g.rows, cx, y + 1, shadow);
        inkPixels(ctx, g.rows, cx + 1, y + 1, shadow);
      }
      inkPixels(ctx, g.rows, cx, y, color);
    }
    cx += g.advance;
    i++;
  }
  return cx;
}
