// ORIGINAL hand-designed bitmap fonts for the OCR bench (no Nintendo assets).
//
// GB_THIN  - Game Boy style 8x8 tile font, 1-px strokes (Gen 2 feel).
// GB_BOLD  - Game Boy style 8x8 tile font with 2-px vertical stems
//            (Gen 1 feel). Derived from GB_THIN by stem dilation plus
//            hand-drawn overrides for glyphs the dilation would clog.
// GBA      - Gen 3 style proportional font (5-6 px advance, 11 px glyph
//            box, 16 px line pitch) drawn with a 1-px drop shadow. Derived
//            from GB_THIN by a fixed vertical stretch (rows 1, 5 and 7 are
//            doubled) and per-glyph proportional widths.
//
// Glyphs are arrays of 8-char strings ('#' = ink, '.' = paper). Caps sit on
// rows 0-6, the x-height is rows 2-6, descenders use row 7.
//
// Special tiles (Pokemon-style), keyed by private-use code points so scene
// texts can embed them:
//     'PK' ligature tile        'MN' ligature tile
//     ':L' level tile            'HP' label tile
//   '▼' dialog continue arrow, '▶' menu cursor, '♂', '♀', '…'
// The 'é' of POKéMON is the regular 'é' glyph (as in the games).

